use crate::Fields;
use serde::{
    Deserialize, Deserializer, Serialize,
    de::{self, DeserializeSeed, EnumAccess, Unexpected, VariantAccess, Visitor},
};
use std::{fmt, marker::PhantomData};

pub trait EntityFields {
    type Fields;

    /// Returns the field from its PascalCase name.
    #[inline]
    fn field_by_name(_name: &str) -> Option<Self::Fields> {
        None
    }
}

/// Private: used by macros.
///
/// Resolves the field of an entity by its PascalCase name, or `None` when the entity has no
/// fields enum (autoref specialization over [`__FieldOfEntity`] and [`__FieldOfNone`]).
#[doc(hidden)]
pub struct __FieldOf<E>(PhantomData<E>);

impl<E> __FieldOf<E> {
    #[allow(clippy::new_without_default)]
    #[inline]
    pub const fn new() -> Self {
        Self(PhantomData)
    }
}

#[doc(hidden)]
pub trait __FieldOfEntity {
    fn __field(&self, name: &str) -> Option<Box<dyn Fields>>;
}

impl<E> __FieldOfEntity for __FieldOf<E>
where
    E: EntityFields,
    E::Fields: Fields,
{
    #[inline]
    fn __field(&self, name: &str) -> Option<Box<dyn Fields>> {
        E::field_by_name(name).map(|f| Box::new(f) as Box<dyn Fields>)
    }
}

#[doc(hidden)]
pub trait __FieldOfNone {
    #[inline]
    fn __field(&self, _name: &str) -> Option<Box<dyn Fields>> {
        None
    }
}

impl<E> __FieldOfNone for &__FieldOf<E> {}

#[derive(Clone, Deserialize, Eq, Hash, PartialEq, Serialize)]
#[serde(untagged)]
pub enum FieldsOrStr<Fields> {
    Fields(Fields),
    String(String),
}

/// Deserializes the fields enum generated by `MssqlSave` and returns the index of the variant.
///
/// Accepts the same input as `#[derive(Deserialize)]` on a unit-only enum, but is compiled once
/// instead of once per entity.
#[doc(hidden)]
pub fn _deserialize_fields<'de, D: Deserializer<'de>>(
    deserializer: D,
    name: &'static str,
    variants: &'static [&'static str],
) -> Result<usize, D::Error> {
    deserializer.deserialize_enum(name, variants, FieldsVisitor { name, variants })
}

struct FieldsVisitor {
    name: &'static str,
    variants: &'static [&'static str],
}

impl<'de> Visitor<'de> for FieldsVisitor {
    type Value = usize;

    fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(f, "enum {}", self.name)
    }

    fn visit_enum<A: EnumAccess<'de>>(self, data: A) -> Result<usize, A::Error> {
        let (index, variant) = data.variant_seed(VariantIdentifier(self.variants))?;
        variant.unit_variant()?;
        Ok(index)
    }
}

struct VariantIdentifier(&'static [&'static str]);

impl<'de> DeserializeSeed<'de> for VariantIdentifier {
    type Value = usize;

    fn deserialize<D: Deserializer<'de>>(self, deserializer: D) -> Result<usize, D::Error> {
        deserializer.deserialize_identifier(self)
    }
}

impl Visitor<'_> for VariantIdentifier {
    type Value = usize;

    fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
        f.write_str("variant identifier")
    }

    fn visit_u64<E: de::Error>(self, v: u64) -> Result<usize, E> {
        usize::try_from(v)
            .ok()
            .filter(|&i| i < self.0.len())
            .ok_or_else(|| {
                let msg = format!("variant index 0 <= i < {}", self.0.len());
                E::invalid_value(Unexpected::Unsigned(v), &msg.as_str())
            })
    }

    fn visit_str<E: de::Error>(self, v: &str) -> Result<usize, E> {
        self.0
            .iter()
            .position(|n| *n == v)
            .ok_or_else(|| E::unknown_variant(v, self.0))
    }

    fn visit_bytes<E: de::Error>(self, v: &[u8]) -> Result<usize, E> {
        match std::str::from_utf8(v) {
            Ok(s) => self.visit_str(s),
            Err(_) => Err(E::unknown_variant(&String::from_utf8_lossy(v), self.0)),
        }
    }
}

#[cfg(test)]
#[allow(clippy::indexing_slicing, clippy::panic, clippy::unwrap_used)]
mod tests {
    use super::{_deserialize_fields, FieldsOrStr};
    use serde::{Deserialize, Deserializer};

    #[derive(Clone, Copy, Debug, Deserialize, PartialEq)]
    #[serde(rename_all = "camelCase")]
    enum Derived {
        FirstName,
        Age,
    }

    #[derive(Clone, Copy, Debug, PartialEq)]
    enum Manual {
        FirstName,
        Age,
    }

    impl<'de> Deserialize<'de> for Manual {
        fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
            // Same name as the derived enum so the error messages are comparable.
            let i = _deserialize_fields(d, "Derived", &["firstName", "age"])?;
            Ok([Self::FirstName, Self::Age][i])
        }
    }

    fn same(json: &str) {
        let as_u8 = |r: Result<u8, String>| r;

        // Directly from the text.
        let d = serde_json::from_str::<Derived>(json)
            .map(|v| v as u8)
            .map_err(|e| e.to_string());
        let m = serde_json::from_str::<Manual>(json)
            .map(|v| v as u8)
            .map_err(|e| e.to_string());
        assert_eq!(as_u8(d), as_u8(m), "text {json}");

        // From a `Value`, another `Deserializer`.
        if let Ok(value) = serde_json::from_str::<serde_json::Value>(json) {
            let d = Derived::deserialize(&value)
                .map(|v| v as u8)
                .map_err(|e| e.to_string());
            let m = Manual::deserialize(&value)
                .map(|v| v as u8)
                .map_err(|e| e.to_string());
            assert_eq!(d, m, "value {json}");
        }

        // Buffered by `#[serde(untagged)]`.
        let d = serde_json::from_str::<FieldsOrStr<Derived>>(json)
            .map(|v| match v {
                FieldsOrStr::Fields(f) => Ok(f as u8),
                FieldsOrStr::String(s) => Err(s),
            })
            .map_err(|e| e.to_string());
        let m = serde_json::from_str::<FieldsOrStr<Manual>>(json)
            .map(|v| match v {
                FieldsOrStr::Fields(f) => Ok(f as u8),
                FieldsOrStr::String(s) => Err(s),
            })
            .map_err(|e| e.to_string());
        assert_eq!(d, m, "untagged {json}");
    }

    #[test]
    fn matches_derive() {
        for json in [
            r#""firstName""#,
            r#""age""#,
            r#""FirstName""#,
            r#""first_name""#,
            r#""other""#,
            r#""""#,
            r#""\u0061ge""#,
            r#"{"age":null}"#,
            r#"{"age":1}"#,
            r#"{"other":null}"#,
            r#"{"age":null,"firstName":null}"#,
            r#"{}"#,
            r#"["age"]"#,
            "0",
            "1",
            "2",
            "18446744073709551615",
            "-1",
            "1.5",
            "true",
            "null",
        ] {
            same(json);
        }
    }

    #[test]
    fn untagged_falls_back_to_string() {
        let v: Vec<FieldsOrStr<Manual>> = serde_json::from_str(r#"["age","other"]"#).unwrap();
        assert!(matches!(v[0], FieldsOrStr::Fields(Manual::Age)));
        assert!(matches!(&v[1], FieldsOrStr::String(s) if s == "other"));
    }
}
